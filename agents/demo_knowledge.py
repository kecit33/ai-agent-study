def answer(question: str):
    """按关键词匹配返回真实讲解文本；未命中返回 None。"""
    q = (question or "").lower()
    if not q.strip():
        return None
    best = None
    best_score = 0
    for keywords, text in _ENTRIES:
        score = 0
        for kw in keywords:
            if kw in q:
                # 越长/越具体的词权重越高，降低单字误命中
                score += max(1, len(kw))
        if score > best_score:
            best_score = score
            best = text
    return best if best_score >= 1 else None
